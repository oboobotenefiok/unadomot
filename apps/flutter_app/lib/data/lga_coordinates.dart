  static LatLng? forLga(String state, String lga) {
    final list = _points[state];
    if (list == null) return null;
    final options = NigeriaLocations.lgas[state];
    if (options == null) return null;
    final index = options.indexOf(lga);
    if (index < 0 || index >= list.length) return null;
    final point = list[index];
    return LatLng(point[0], point[1]);
  }

  static bool covers(String state) => _points.containsKey(state);
